// Regenerates the README's "Supported appliances" tables from the drivers' `models` exports.
//
//   npm run device-list            rewrite README.md
//   npm run device-list -- --check exit 1 if README.md is out of date
//
// Rows are grouped by category and sorted by their first model ID.

import fs from 'node:fs'
import { fileURLToPath } from 'node:url'
import * as prettier from 'prettier'
import { CATEGORIES, drivers, type ModelEntry } from '@/cloud/registry'

export const README = fileURLToPath(new URL('../README.md', import.meta.url))
const START = '<!-- device-list:start (generated by `npm run device-list`, edit the drivers instead) -->'
const END = '<!-- device-list:end -->'

// Prettier then drops the escapes markdown doesn't need, which matches how the table was hand-written
const escape = (s: string) => s.replace(/([\\_*|])/g, '\\$1')

function row(entry: ModelEntry) {
    const ids = entry.ids.join(', ') + (entry.platform === 'thinq1' ? ' (ThinQ1)' : '')
    return `| ${escape(ids)} | ${escape(entry.appliance)} | ${escape(entry.support)} |`
}

export function renderTables(entries: ModelEntry[]) {
    const out: string[] = []
    for (const category of CATEGORIES) {
        const rows = entries
            .filter((e) => e.category === category)
            .sort((a, b) => a.ids[0].localeCompare(b.ids[0], 'en'))
        if (!rows.length) continue
        out.push(`#### ${category}`, '', '| ThinQ model | Appliance | Support |', '| --- | --- | --- |')
        out.push(...rows.map(row), '')
    }
    return out.join('\n')
}

export async function renderReadme(current: string) {
    const start = current.indexOf(START)
    const end = current.indexOf(END)
    if (start < 0 || end < start) throw new Error('README.md: device-list markers not found')

    const tables = renderTables(drivers.flatMap((d) => d.models))
    const next = current.slice(0, start + START.length) + '\n\n' + tables + '\n' + current.slice(end)
    const options = await prettier.resolveConfig(README)
    return prettier.format(next, { ...options, filepath: README })
}

if (process.argv[1] && fileURLToPath(import.meta.url) === fs.realpathSync(process.argv[1])) {
    const current = fs.readFileSync(README, 'utf8')
    const next = await renderReadme(current)
    if (process.argv.includes('--check')) {
        if (next !== current) {
            console.error('README.md device list is out of date; run `npm run device-list`')
            process.exit(1)
        }
    } else if (next !== current) {
        fs.writeFileSync(README, next)
        console.log('README.md updated')
    }
}
